/**
 * `data/aliases.json` → Cloudflare Pages `_redirects` 생성 (docs/05 §3).
 *
 * static export 는 Next redirects 를 지원하지 않으므로, alias→canonical 301 은
 * Pages 의 `_redirects` 파일로 처리한다. 정적 룰 한도는 2,000줄 — 초과 시 빌드를
 * 실패시켜 "수요 있는 alias만 301, 나머지는 캐노니컬 태그" 원칙을 강제한다.
 * GPU 비교(10-19 D106)는 뒤집은 순서 슬러그(`/compare/{b}-vs-{a}`)를 정순으로 301 — `compareRedirects`.
 */
import { readFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { reversedCompareSlugs } from '../apps/web/content/compares';

/** Cloudflare Pages 정적 `_redirects` 룰 한도. source: https://developers.cloudflare.com/pages/configuration/redirects/ */
export const CF_PAGES_REDIRECT_LINE_LIMIT = 2000;

export type AliasRecord = {
  /** 요청이 들어오는 alias 경로 (예: `/gpu/rtx-4060-ti-16gb`) */
  from: string;
  /** 리다이렉트 대상 canonical 경로 (예: `/gpu/rtx-4060-ti`) */
  to: string;
};

/** C0 제어문자(0x00~0x1f)·DEL(0x7f) 포함 여부 — 정규식 이스케이프 없이 코드포인트로 검사. */
export function hasControlChars(value: string): boolean {
  for (let i = 0; i < value.length; i += 1) {
    const code = value.charCodeAt(i);
    if (code < 0x20 || code === 0x7f) return true;
  }
  return false;
}

/**
 * 리다이렉트 경로 검증 (외부 리뷰 반영): `^/[^\s?#]*$` — `/`로 시작, 공백·`?`·`#` 금지
 * (_redirects 는 공백 구분 포맷이라 인젝션 방어) + 제어문자 거부.
 */
const PATH_PATTERN = /^\/[^\s?#]*$/;

export function isValidRedirectPath(path: string): boolean {
  return PATH_PATTERN.test(path) && !hasControlChars(path);
}

function isAliasRecord(value: unknown): value is AliasRecord {
  if (typeof value !== 'object' || value === null) return false;
  const record = value as Record<string, unknown>;
  return (
    typeof record.from === 'string' &&
    isValidRedirectPath(record.from) &&
    typeof record.to === 'string' &&
    isValidRedirectPath(record.to)
  );
}

export function buildRedirects(aliases: readonly AliasRecord[]): string {
  for (const alias of aliases) {
    if (!isValidRedirectPath(alias.from) || !isValidRedirectPath(alias.to)) {
      throw new Error(`invalid redirect path in alias: ${JSON.stringify(alias)}`);
    }
  }

  const output = `${[
    '# generated by scripts/build-redirects.ts — do not edit by hand',
    // i18n A안 (docs/05 §1 스파이크 결정): en 은 루트에 서빙되므로
    // 잔존 /en/* 링크·북마크를 루트로 301 정리한다. /en 단독도 포함.
    '/en / 301',
    '/en/* /:splat 301',
    ...aliases.map((alias) => `${alias.from} ${alias.to} 301`),
  ].join('\n')}\n`;

  // 한도는 최종 문자열의 룰 줄 수 기준 (외부 리뷰 반영 — 생성 배열이 아닌 산출물 기준)
  const ruleCount = output
    .split('\n')
    .filter((line) => line.trim() !== '' && !line.startsWith('#')).length;
  if (ruleCount > CF_PAGES_REDIRECT_LINE_LIMIT) {
    throw new Error(
      `_redirects has ${ruleCount} rules — exceeds Cloudflare Pages limit of ${CF_PAGES_REDIRECT_LINE_LIMIT}. ` +
        'Keep only high-demand aliases as 301s; the rest must rely on canonical tags (docs/05 §3).',
    );
  }

  return output;
}

/**
 * GPU 비교 뒤집은 순서 → 정순 301 (10-19 D106) — en·ko 둘 다. 레지스트리 전 쌍(초안 포함 — 게시해도 URL 규칙이 바뀌지 않게).
 * 쌍 12개(COMPARE_MAX) × 2 로캘 = 24줄 — 한도(2,000)에 비해 작다
 */
export function compareRedirects(): AliasRecord[] {
  return reversedCompareSlugs().flatMap(({ reversed, slug }) => [
    { from: `/compare/${reversed}`, to: `/compare/${slug}` },
    { from: `/ko/compare/${reversed}`, to: `/ko/compare/${slug}` },
  ]);
}

export function loadAliases(repoRoot: string): AliasRecord[] {
  const raw: unknown = JSON.parse(readFileSync(resolve(repoRoot, 'data/aliases.json'), 'utf8'));
  if (!Array.isArray(raw)) {
    throw new Error('data/aliases.json must be a JSON array');
  }
  const invalid = raw.filter((entry) => !isAliasRecord(entry));
  if (invalid.length > 0) {
    throw new Error(
      `data/aliases.json has ${invalid.length} invalid record(s) — each record needs {from: "/…", to: "/…"} with no whitespace/query/control characters`,
    );
  }
  return raw as AliasRecord[];
}
