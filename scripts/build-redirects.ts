/**
 * `data/aliases.json` → Cloudflare Pages `_redirects` 생성 (docs/05 §3).
 *
 * static export 는 Next redirects 를 지원하지 않으므로, alias→canonical 301 은
 * Pages 의 `_redirects` 파일로 처리한다. 정적 룰 한도는 2,000줄 — 초과 시 빌드를
 * 실패시켜 "수요 있는 alias만 301, 나머지는 캐노니컬 태그" 원칙을 강제한다.
 *
 * P0-1 스텁 범위: aliases.json 은 빈 배열이며, 스키마(from/to)와 한도 가드,
 * `/en/*` 정리 룰만 배선한다. 실제 alias 시드는 P0-3(docs/03).
 */
import { readFileSync } from 'node:fs';
import { resolve } from 'node:path';

/** Cloudflare Pages 정적 `_redirects` 룰 한도. source: https://developers.cloudflare.com/pages/configuration/redirects/ */
export const CF_PAGES_REDIRECT_LINE_LIMIT = 2000;

export type AliasRecord = {
  /** 요청이 들어오는 alias 경로 (예: `/gpu/rtx-4060-ti-16gb`) */
  from: string;
  /** 리다이렉트 대상 canonical 경로 (예: `/gpu/rtx-4060-ti`) */
  to: string;
};

function isAliasRecord(value: unknown): value is AliasRecord {
  if (typeof value !== 'object' || value === null) return false;
  const record = value as Record<string, unknown>;
  return (
    typeof record.from === 'string' &&
    record.from.startsWith('/') &&
    typeof record.to === 'string' &&
    record.to.startsWith('/')
  );
}

export function buildRedirects(aliases: readonly AliasRecord[]): string {
  const lines: string[] = [
    '# generated by scripts/build-redirects.ts — do not edit by hand',
    // i18n A안 (docs/05 §1 스파이크 결정): en 은 루트에 서빙되므로
    // 잔존 /en/* 링크·북마크를 루트로 301 정리한다. /en 단독도 포함.
    '/en / 301',
    '/en/* /:splat 301',
    ...aliases.map((alias) => `${alias.from} ${alias.to} 301`),
  ];

  const ruleCount = lines.filter((line) => !line.startsWith('#')).length;
  if (ruleCount > CF_PAGES_REDIRECT_LINE_LIMIT) {
    throw new Error(
      `_redirects has ${ruleCount} rules — exceeds Cloudflare Pages limit of ${CF_PAGES_REDIRECT_LINE_LIMIT}. ` +
        'Keep only high-demand aliases as 301s; the rest must rely on canonical tags (docs/05 §3).',
    );
  }

  return `${lines.join('\n')}\n`;
}

export function loadAliases(repoRoot: string): AliasRecord[] {
  const raw: unknown = JSON.parse(readFileSync(resolve(repoRoot, 'data/aliases.json'), 'utf8'));
  if (!Array.isArray(raw)) {
    throw new Error('data/aliases.json must be a JSON array');
  }
  const invalid = raw.filter((entry) => !isAliasRecord(entry));
  if (invalid.length > 0) {
    throw new Error(
      `data/aliases.json has ${invalid.length} invalid record(s) — each record needs {from: "/…", to: "/…"}`,
    );
  }
  return raw as AliasRecord[];
}
